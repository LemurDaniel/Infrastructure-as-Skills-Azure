#!/usr/bin/env python3
"""Writes references/abbreviations.md from the `abbreviations:` block of naming.default.yaml.

The YAML is the source - the naming provider bundles it - and the Markdown is the readable
reference: one table per category, the categories taken from the `#////` comments of the
block. Commented-out entries are left out, as the provider leaves them out.

    python write_abbreviations.py           # writes references/abbreviations.md
    python write_abbreviations.py --check   # writes nothing, exit 1 when the file is stale

Line-based, no PyYAML: the categories live in comments, which a YAML parser drops.
"""
import argparse
import re
import sys
from pathlib import Path

HERE = Path(__file__).resolve().parent
SOURCE = HERE.parent / "references" / "naming.default.yaml"
TARGET = HERE.parent / "references" / "abbreviations.md"

PROVIDER = re.compile(r"^  (\w+):\s*$")
CATEGORY = re.compile(r"^\s*#////\s*(.+?)\s*$")
ENTRY = re.compile(r"^\s{4}([^#\s][^:]*(?::[^:\s][^:]*)*)::([\w.-]+):\s*(\S+)\s*$")

HEADER = """# Abbreviations

<!-- Generated by scripts/write_abbreviations.py from naming.default.yaml. Do not edit by hand:
     change the YAML and run the script; check_repo_consistency.py fails on a stale file. -->

The type prefixes of the plugin's naming convention, the `<TYPE>` part of every pattern in
[naming.md](naming.md). The source is the `abbreviations:` block of
[naming.default.yaml](naming.default.yaml), which follows the
[CAF abbreviations](https://learn.microsoft.com/azure/cloud-adoption-framework/ready/azure-best-practices/resource-abbreviations);
a repository's `naming.yaml` overrides single entries.

A name takes the `default` variant unless the question set selects another one
(`naming_id`, or the resource's `kind`, e.g. `Microsoft.Web/sites::function`). A question
set's `naming.abbreviation` mirrors one of the rows here.
"""


def parse(text):
    """-> [(provider, [(category, [(type, variant, abbreviation)])])] in file order."""
    providers, in_block, category = [], False, None
    for line in text.splitlines():
        if re.match(r"^abbreviations:\s*$", line):
            in_block = True
            continue
        if not in_block:
            continue
        if re.match(r"^\S", line):
            break
        m = PROVIDER.match(line)
        if m:
            providers.append((m.group(1), []))
            category = None
            continue
        m = CATEGORY.match(line)
        if m and providers:
            category = m.group(1)
            providers[-1][1].append((category, []))
            continue
        m = ENTRY.match(line)
        if m and providers:
            if category is None:
                providers[-1][1].append(("Other", []))
                category = "Other"
            providers[-1][1][-1][1].append(m.groups())
    return providers


def render(providers):
    out = [HEADER]
    for provider, categories in providers:
        out.append(f"## {provider}\n")
        for category, entries in categories:
            if not entries:
                continue
            out.append(f"### {category}\n")
            out.append("| Type | Variant | Abbreviation |")
            out.append("|---|---|---|")
            for rtype, variant, abbr in entries:
                out.append(f"| `{rtype}` | `{variant}` | `{abbr}` |")
            out.append("")
    return "\n".join(out).rstrip() + "\n"


def main():
    ap = argparse.ArgumentParser(description=__doc__.splitlines()[0])
    ap.add_argument("--check", action="store_true", help="write nothing, exit 1 when stale")
    args = ap.parse_args()

    providers = parse(SOURCE.read_text(encoding="utf-8"))
    if not any(entries for _, cats in providers for _, entries in cats):
        sys.exit(f"error: no abbreviations found in {SOURCE.name}")
    text = render(providers)
    current = TARGET.read_text(encoding="utf-8") if TARGET.is_file() else None

    if args.check:
        if current != text:
            print(f"stale: {TARGET.name} differs from {SOURCE.name} - run write_abbreviations.py")
            return 1
        print(f"ok: {TARGET.name} matches {SOURCE.name}")
        return 0
    if current != text:
        TARGET.write_text(text, encoding="utf-8", newline="\n")
        print(f"wrote {TARGET.name}")
    else:
        print(f"unchanged: {TARGET.name}")
    return 0


if __name__ == "__main__":
    sys.exit(main())
